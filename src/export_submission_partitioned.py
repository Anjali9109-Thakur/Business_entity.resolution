"""Create final TSVs with disk-partitioned aggregation for low-RAM machines.

The normal exporter groups all 52M candidate records at once, which can exceed
8 GB RAM because DuckDB's string_agg state is not externally spillable.  This
version first partitions the already-created candidate table and score Parquet
by a deterministic Source-1 hash.  Each partition is then small enough to
aggregate independently, and the resulting TSV parts are streamed together.
"""

from __future__ import annotations

import argparse
import shutil
from pathlib import Path

import duckdb


def valid_table_name(name: str) -> bool:
    return name.replace("_", "").isalnum()


def sql_literal(path: Path) -> str:
    return "'" + str(path.resolve()).replace("'", "''") + "'"


def copy_partitioned_parquet(
    connection: duckdb.DuckDBPyConnection,
    query: str,
    output_dir: Path,
) -> None:
    connection.execute(
        f"COPY ({query}) TO {sql_literal(output_dir)} "
        "(FORMAT PARQUET, COMPRESSION ZSTD, PARTITION_BY (source_bucket))"
    )


def copy_part(
    connection: duckdb.DuckDBPyConnection,
    query: str,
    output_path: Path,
) -> None:
    connection.execute(
        f"COPY ({query}) TO {sql_literal(output_path)} "
        "(HEADER false, DELIMITER '\\t')"
    )


def append_part_rows(part_path: Path, destination, seen_sources: set[str]) -> int:
    """Append a two-column TSV part and return its number of Source-1 rows."""
    rows = 0
    with part_path.open("r", encoding="utf-8", newline="") as source:
        for line in source:
            if not line.strip():
                continue
            source1_id, separator, _ = line.partition("\t")
            if not separator:
                raise RuntimeError(f"Malformed temporary TSV row: {line[:100]!r}")
            if source1_id in seen_sources:
                raise RuntimeError(f"Duplicate Source-1 ID across partitions: {source1_id}")
            seen_sources.add(source1_id)
            destination.write(line)
            rows += 1
    return rows


def append_empty_rows(
    connection: duckdb.DuckDBPyConnection,
    destination,
    represented_sources: set[str],
) -> int:
    """Append every test S1 that had no row in a corresponding TSV part."""
    written = 0
    reader = connection.execute("SELECT entity_id FROM test_s1").to_arrow_reader(
        batch_size=100_000
    )
    for batch in reader:
        for source1_id in batch.column(0).to_pylist():
            if source1_id not in represented_sources:
                destination.write(f"{source1_id}\t\n")
                written += 1
    return written


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--database", default="work/entity_resolution.duckdb", type=Path)
    parser.add_argument("--candidate-table", required=True)
    parser.add_argument("--scores", required=True, type=Path)
    parser.add_argument("--threshold", required=True, type=float)
    parser.add_argument("--output-dir", default="output", type=Path)
    parser.add_argument("--work-dir", default="work/partitioned_export", type=Path)
    parser.add_argument("--buckets", default=128, type=int)
    parser.add_argument("--memory-limit", default="3GB")
    args = parser.parse_args()
    if not valid_table_name(args.candidate_table):
        raise SystemExit("--candidate-table may contain only letters, digits, and underscores.")
    if not args.scores.is_file():
        raise SystemExit(f"Scores file not found: {args.scores}")
    if not 0.0 <= args.threshold <= 1.0:
        raise SystemExit("--threshold must be between 0 and 1.")
    if args.buckets < 2:
        raise SystemExit("--buckets must be at least 2.")

    args.output_dir.mkdir(parents=True, exist_ok=True)
    # This explicitly named work directory contains only temporary partitions
    # generated by this command, so a prior interrupted run may be removed.
    if args.work_dir.exists():
        shutil.rmtree(args.work_dir)
    candidate_partition_dir = args.work_dir / "candidate_partitions"
    score_partition_dir = args.work_dir / "score_partitions"
    part_dir = args.work_dir / "tsv_parts"
    temp_dir = args.work_dir / "duckdb_temp"
    for directory in (candidate_partition_dir, score_partition_dir, part_dir, temp_dir):
        directory.mkdir(parents=True, exist_ok=True)

    matching_path = args.output_dir / "matching_results.tsv"
    candidate_path = args.output_dir / "candidate_pairs.tsv"
    for output_path in (matching_path, candidate_path):
        if output_path.exists():
            output_path.unlink()

    connection = duckdb.connect(str(args.database.resolve()))
    connection.execute(f"SET memory_limit = '{args.memory_limit}'")
    connection.execute("SET threads = 1")
    connection.execute("SET preserve_insertion_order = false")
    connection.execute(f"SET temp_directory = {sql_literal(temp_dir)}")
    scores_path = sql_literal(args.scores)

    print(f"Partitioning {args.candidate_table} into {args.buckets} buckets...")
    copy_partitioned_parquet(
        connection,
        f"""
        SELECT source1_entity_id, candidate_entity_id, candidate_rank,
               hash(source1_entity_id) % {args.buckets} AS source_bucket
        FROM {args.candidate_table}
        """,
        candidate_partition_dir,
    )
    print("Partitioning existing model scores...")
    copy_partitioned_parquet(
        connection,
        f"""
        SELECT source1_entity_id, candidate_entity_id, match_probability,
               hash(source1_entity_id) % {args.buckets} AS source_bucket
        FROM read_parquet({scores_path})
        """,
        score_partition_dir,
    )

    candidate_parts: list[Path] = []
    matching_parts: list[Path] = []
    for bucket in range(args.buckets):
        candidate_glob = candidate_partition_dir / f"source_bucket={bucket}" / "*.parquet"
        score_glob = score_partition_dir / f"source_bucket={bucket}" / "*.parquet"
        if not list(candidate_glob.parent.glob("*.parquet")):
            continue
        candidate_relation = f"read_parquet({sql_literal(candidate_glob)})"
        candidate_part = part_dir / f"candidates_{bucket:03d}.tsv"
        copy_part(
            connection,
            f"""
            SELECT
                source1_entity_id,
                string_agg(candidate_entity_id, ',' ORDER BY candidate_rank,
                           candidate_entity_id) AS candidate_entity_ids
            FROM {candidate_relation}
            GROUP BY source1_entity_id
            """,
            candidate_part,
        )
        candidate_parts.append(candidate_part)

        if not list(score_glob.parent.glob("*.parquet")):
            raise RuntimeError(f"Scores missing bucket {bucket}; cannot safely export.")
        score_relation = f"read_parquet({sql_literal(score_glob)})"
        matching_part = part_dir / f"matches_{bucket:03d}.tsv"
        copy_part(
            connection,
            f"""
            SELECT
                candidate.source1_entity_id,
                string_agg(candidate.candidate_entity_id, ',' ORDER BY candidate.candidate_rank,
                           candidate.candidate_entity_id) AS matched_entity_ids
            FROM {candidate_relation} AS candidate
            INNER JOIN {score_relation} AS score
                USING (source1_entity_id, candidate_entity_id)
            WHERE score.match_probability >= {args.threshold}
            GROUP BY candidate.source1_entity_id
            """,
            matching_part,
        )
        matching_parts.append(matching_part)
        if (bucket + 1) % 16 == 0 or bucket + 1 == args.buckets:
            print(f"  aggregated bucket {bucket + 1}/{args.buckets}")

    candidate_sources: set[str] = set()
    matching_sources: set[str] = set()
    with candidate_path.open("w", encoding="utf-8", newline="") as candidate_output:
        candidate_output.write("source1_entity_id\tcandidate_entity_ids\n")
        nonempty_candidates = sum(
            append_part_rows(part, candidate_output, candidate_sources) for part in candidate_parts
        )
        empty_candidates = append_empty_rows(connection, candidate_output, candidate_sources)
    with matching_path.open("w", encoding="utf-8", newline="") as matching_output:
        matching_output.write("source1_entity_id\tmatched_entity_ids\n")
        nonempty_matches = sum(
            append_part_rows(part, matching_output, matching_sources) for part in matching_parts
        )
        empty_matches = append_empty_rows(connection, matching_output, matching_sources)
    connection.close()

    print(
        f"Wrote {candidate_path}: {nonempty_candidates:,} non-empty and "
        f"{empty_candidates:,} empty rows."
    )
    print(
        f"Wrote {matching_path}: {nonempty_matches:,} non-empty and "
        f"{empty_matches:,} empty rows."
    )


if __name__ == "__main__":
    main()
